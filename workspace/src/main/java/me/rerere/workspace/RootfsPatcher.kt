package me.rerere.workspace

import java.io.File
import java.nio.file.Files

class RootfsPatcher {
    fun patch(
        linuxDir: File,
        options: RootfsPatchOptions = RootfsPatchOptions(),
    ) {
        val etcDir = File(linuxDir, "etc")
        if (!etcDir.isDirectory && !WorkspaceManager.isUsableRootfs(linuxDir)) return
        etcDir.mkdirs()

        ensureRootfsDns(etcDir, options.nameservers)
        ensureHosts(etcDir, options.hostname)
        ensureHostname(etcDir, options.hostname)
        ensurePasswd(etcDir)
        ensureLocale(etcDir, options.locale)
        ensureGroupNames(etcDir, options.groupIds.ifEmpty { currentSupplementaryGroupIds() })
        ensureTempDirs(linuxDir)
        ensureAndroidProfile(linuxDir)
        ensureAptProotConfig(linuxDir)
        cleanupLegacyTrashWrappers(linuxDir)
        ensureHostBridgeScript(linuxDir)
    }

    fun patch(linuxDir: File, nameservers: List<String>) {
        patch(linuxDir, RootfsPatchOptions(nameservers = nameservers))
    }

    private fun ensureRootfsDns(
        etcDir: File,
        nameservers: List<String>,
    ) {
        val resolvConf = File(etcDir, "resolv.conf")
        val explicitServers = nameservers.filter { it.isNotBlank() }.distinct().take(MAX_DNS_SERVERS)
        val shouldWrite = when {
            Files.isSymbolicLink(resolvConf.toPath()) -> true
            !resolvConf.exists() -> true
            !resolvConf.isFile -> true
            explicitServers.isNotEmpty() -> true
            else -> resolvConf.readText()
                .lineSequence()
                .filter { it.trimStart().startsWith("nameserver ") }
                .none { line ->
                    val server = line.trim().removePrefix("nameserver").trim()
                    server.isNotBlank() && server !in LOCAL_RESOLVERS
                }
        }
        if (!shouldWrite) return

        val servers = explicitServers.ifEmpty { DEFAULT_DNS_SERVERS }
        val content = buildString {
            appendLine("# Generated by RikkaHub workspace.")
            servers.forEach { appendLine("nameserver $it") }
            appendLine("options edns0 trust-ad")
        }
        writeRootfsFile(etcDir.parentFile ?: return, "etc/resolv.conf", content)
    }

    private fun ensureHosts(etcDir: File, hostname: String) {
        val hosts = File(etcDir, "hosts")
        val lines = if (hosts.isFile) hosts.readLines() else emptyList()
        val hasIpv4Localhost = lines.any { line ->
            val normalized = line.substringBefore('#').trim().split(WHITESPACE_REGEX)
            normalized.firstOrNull() == "127.0.0.1" && "localhost" in normalized.drop(1)
        }
        val hasIpv6Localhost = lines.any { line ->
            val normalized = line.substringBefore('#').trim().split(WHITESPACE_REGEX)
            normalized.firstOrNull() == "::1" && "localhost" in normalized.drop(1)
        }
        if (hasIpv4Localhost && hasIpv6Localhost) return

        hosts.parentFile?.mkdirs()
        hosts.appendText(
            buildString {
                if (hosts.exists() && hosts.length() > 0 && !hosts.readText().endsWith('\n')) {
                    appendLine()
                }
                if (!hasIpv4Localhost) {
                    append("127.0.0.1 localhost")
                    if (hostname.isNotBlank() && hostname != "localhost") {
                        append(" ")
                        append(hostname)
                    }
                    appendLine()
                }
                if (!hasIpv6Localhost) {
                    appendLine("::1 localhost ip6-localhost ip6-loopback")
                }
            }
        )
    }

    private fun ensureHostname(etcDir: File, hostname: String) {
        val target = File(etcDir, "hostname")
        if (target.isFile && target.readText().trim().isNotBlank()) return
        target.writeText("${hostname.ifBlank { DEFAULT_HOSTNAME }}\n")
    }

    private fun ensurePasswd(etcDir: File) {
        val passwd = File(etcDir, "passwd")
        if (!passwd.exists()) {
            passwd.writeText("root:x:0:0:root:/root:/bin/sh\n")
        }
    }

    private fun ensureLocale(etcDir: File, locale: String) {
        val defaultDir = File(etcDir, "default").apply { mkdirs() }
        val target = File(defaultDir, "locale")
        val lines = if (target.isFile) target.readLines().toMutableList() else mutableListOf()
        if (lines.any { it.trim().startsWith("LANG=") }) return
        lines += "LANG=$locale"
        target.writeText(lines.joinToString(separator = "\n", postfix = "\n"))
    }

    private fun ensureGroupNames(etcDir: File, groupIds: List<Long>) {
        val target = File(etcDir, "group")
        if (!target.exists()) {
            target.writeText("root:x:0:\n")
        }
        val lines = target.readLines().toMutableList()
        val existingIds = lines.mapNotNull { line ->
            line.split(':').getOrNull(2)?.toLongOrNull()
        }.toSet()
        val existingNames = lines.mapNotNull { line ->
            line.substringBefore(':').takeIf { it.isNotBlank() }
        }.toSet()
        val additions = groupIds
            .filter { it > 0 && it !in existingIds }
            .distinct()
            .map { id ->
                val baseName = "android_gid_$id"
                val name = if (baseName in existingNames) "${baseName}_workspace" else baseName
                "$name:x:$id:"
            }
        if (additions.isEmpty()) return

        target.appendText(
            buildString {
                if (target.length() > 0 && !target.readText().endsWith('\n')) {
                    appendLine()
                }
                additions.forEach { appendLine(it) }
            }
        )
    }

    private fun ensureTempDirs(linuxDir: File) {
        listOf("tmp", "var/tmp", "root").forEach { path ->
            File(linuxDir, path).mkdirs()
        }
        listOf(File(linuxDir, "tmp"), File(linuxDir, "var/tmp")).forEach { dir ->
            dir.setReadable(true, false)
            dir.setWritable(true, false)
            dir.setExecutable(true, false)
        }
        File(linuxDir, "root").apply {
            setReadable(true, true)
            setWritable(true, true)
            setExecutable(true, true)
        }
    }

    private fun ensureAndroidProfile(linuxDir: File) {
        writeRootfsFile(linuxDir, "etc/profile.d/rikkahub-android.sh", ANDROID_PROFILE_SCRIPT)
    }

    private fun ensureAptProotConfig(linuxDir: File) {
        if (!File(linuxDir, "etc/apt").isDirectory) return
        writeRootfsFile(linuxDir, "etc/apt/apt.conf.d/99rikkahub-proot", APT_PROOT_CONFIG)
    }

    /**
     * 清理旧版本遗留的 `/usr/local/bin/{rm,rmdir,unlink}` 及 `/usr/local/libexec/rikkahub-sdcard-trash`
     * 回收站包装脚本：现已统一由 `libsdcard_ro.so` 在系统调用层强制只读 (`EROFS`)，不再劫持容器内的标准删除命令。
     */
    private fun cleanupLegacyTrashWrappers(linuxDir: File) {
        listOf(
            "usr/local/bin/rm",
            "usr/local/bin/rmdir",
            "usr/local/bin/unlink",
            "usr/local/libexec/rikkahub-sdcard-trash",
        ).forEach { relativePath ->
            val target = File(linuxDir, relativePath)
            if (target.isFile && runCatching { target.readText().contains(".Trash-RikkaHub") }.getOrDefault(false)) {
                runCatching { target.delete() }
            }
        }
    }

    /**
     * 注入宿主机单向只读诊断客户端 `/usr/local/bin/host-sh`：
     * 仅在当前会话启用了本机存储与只读状态挂载（`/run/host_bridge/endpoint` 存在）时可用。
     */
    private fun ensureHostBridgeScript(linuxDir: File) {
        if (writeRootfsFile(linuxDir, "usr/local/bin/host-sh", HOST_BRIDGE_SCRIPT)) {
            File(linuxDir, "usr/local/bin/host-sh").setExecutable(true, false)
        }
    }

    /**
     * 写 Rootfs 内部文件前先 unlink 已有符号链接，并校验父目录不越出 [linuxDir] 沙盒。
     */
    private fun writeRootfsFile(linuxDir: File, relativePath: String, content: String): Boolean {
        val target = File(linuxDir, relativePath)
        val path = target.toPath()
        val canonicalLinux = linuxDir.canonicalFile
        val parent = target.parentFile ?: return false
        if (parent.exists()) {
            val canonicalParent = parent.canonicalFile
            if (!canonicalParent.startsWith(canonicalLinux)) return false
        }
        if (Files.isSymbolicLink(path)) {
            Files.delete(path)
        } else if (target.isFile && target.readText() == content) {
            return true
        }
        parent.mkdirs()
        if (!parent.canonicalFile.startsWith(canonicalLinux)) return false
        target.writeText(content)
        return true
    }

    private fun currentSupplementaryGroupIds(): List<Long> {
        val status = File("/proc/self/status")
        if (!status.isFile) return emptyList()
        val groups = status.readLines().firstOrNull { it.startsWith("Groups:") } ?: return emptyList()
        return groups
            .removePrefix("Groups:")
            .trim()
            .split(WHITESPACE_REGEX)
            .mapNotNull { it.toLongOrNull() }
    }

    private companion object {
        private const val MAX_DNS_SERVERS = 3
        private const val DEFAULT_HOSTNAME = "localhost"
        private val WHITESPACE_REGEX = Regex("\\s+")
        private val LOCAL_RESOLVERS = setOf(
            "127.0.0.1",
            "127.0.0.53",
            "::1",
        )
        private val DEFAULT_DNS_SERVERS = listOf(
            "1.1.1.1",
            "8.8.8.8",
            "223.5.5.5",
        )

        private const val APT_PROOT_CONFIG = """
APT::Sandbox::User "root";
APT::Sandbox::Seccomp "false";
Acquire::Retries "3";
"""

        private const val ANDROID_PROFILE_SCRIPT = """
# Generated by RikkaHub for PRoot on Android
export HOME="${'$'}{HOME:-/root}"
export USER="${'$'}{USER:-root}"
export LOGNAME="${'$'}{LOGNAME:-root}"
export LANG="${'$'}{LANG:-C.UTF-8}"
export LC_ALL="${'$'}{LC_ALL:-C.UTF-8}"
export TMPDIR="${'$'}{TMPDIR:-/tmp}"
export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"

for _cert in /etc/ssl/certs/ca-certificates.crt /etc/ssl/cert.pem; do
    if [ -f "${'$'}_cert" ]; then
        export SSL_CERT_FILE="${'$'}_cert"
        export CURL_CA_BUNDLE="${'$'}_cert"
        export REQUESTS_CA_BUNDLE="${'$'}_cert"
        export NODE_EXTRA_CA_CERTS="${'$'}_cert"
        break
    fi
done
unset _cert
"""

        private const val HOST_BRIDGE_SCRIPT = """#!/bin/sh
# RikkaHub Read-Only Host Diagnostic Probe (PRoot -> Android Host UID 2000)
# Usage: host-sh [-t SEC] "<readonly_android_query>"
set -eu

ENDPOINT_FILE="/run/host_bridge/endpoint"
if [ ! -f "${'$'}ENDPOINT_FILE" ]; then
    echo "host-sh: Host access is disabled for this conversation. Enable 'Mount device storage (read-only)' in the chat '+' menu if needed." >&2
    exit 126
fi

TIMEOUT=45

while [ "${'$'}#" -gt 0 ]; do
    case "${'$'}1" in
        -t|--timeout)
            shift
            TIMEOUT="${'$'}{1:-45}"
            shift
            ;;
        --)
            shift
            break
            ;;
        -*)
            echo "Usage: host-sh [-t SEC] '<readonly_android_query>'" >&2
            exit 2
            ;;
        *)
            break
            ;;
    esac
done

if [ "${'$'}#" -eq 0 ]; then
    echo "Usage: host-sh [-t SEC] '<readonly_android_query>'" >&2
    exit 2
fi

CMD="${'$'}*"
PORT="${'$'}(sed -n 's/^PORT=//p' "${'$'}ENDPOINT_FILE" | tr -d '\r\n')"
TOKEN="${'$'}(sed -n 's/^TOKEN=//p' "${'$'}ENDPOINT_FILE" | tr -d '\r\n')"

if [ -z "${'$'}PORT" ] || [ -z "${'$'}TOKEN" ]; then
    echo "host-sh: invalid endpoint configuration" >&2
    exit 126
fi

HDR_TMP="${'$'}(mktemp /tmp/host_sh_hdr.XXXXXX)"
OUT_TMP="${'$'}(mktemp /tmp/host_sh_out.XXXXXX)"
cleanup() {
    rm -f "${'$'}HDR_TMP" "${'$'}OUT_TMP"
}
trap cleanup EXIT INT TERM

MAX_TIME=${'$'}((TIMEOUT + 5))

if command -v curl >/dev/null 2>&1; then
    curl -sS -X POST \
        --max-time "${'$'}MAX_TIME" \
        -H "X-Bridge-Token: ${'$'}TOKEN" \
        -H "X-Timeout-Sec: ${'$'}TIMEOUT" \
        -H "Content-Type: text/plain; charset=utf-8" \
        --data-binary "${'$'}CMD" \
        -D "${'$'}HDR_TMP" \
        -o "${'$'}OUT_TMP" \
        "http://127.0.0.1:${'$'}PORT/exec" || {
            echo "host-sh: failed to reach Android HostBridgeDaemon on 127.0.0.1:${'$'}PORT" >&2
            exit 125
        }
elif command -v python3 >/dev/null 2>&1; then
    python3 - "${'$'}PORT" "${'$'}TOKEN" "${'$'}TIMEOUT" "${'$'}MAX_TIME" "${'$'}HDR_TMP" "${'$'}OUT_TMP" "${'$'}CMD" <<'PY'
import sys, urllib.request, urllib.error

port, token, timeout_s, max_time, hdr_path, out_path, cmd = sys.argv[1:8]
req = urllib.request.Request(
    f"http://127.0.0.1:{port}/exec",
    data=cmd.encode("utf-8"),
    headers={
        "X-Bridge-Token": token,
        "X-Timeout-Sec": timeout_s,
        "Content-Type": "text/plain; charset=utf-8",
    },
    method="POST",
)
try:
    with urllib.request.urlopen(req, timeout=int(max_time)) as resp:
        with open(hdr_path, "w", encoding="utf-8") as hf:
            for k, v in resp.headers.items():
                hf.write(f"{k}: {v}\n")
        with open(out_path, "wb") as of:
            of.write(resp.read())
except Exception as e:
    sys.stderr.write(f"host-sh: request failed: {e}\n")
    sys.exit(125)
PY
else
    echo "host-sh: neither curl nor python3 is installed in Rootfs" >&2
    exit 127
fi

EXIT_CODE="${'$'}(grep -i '^X-Exit-Code:' "${'$'}HDR_TMP" | tail -n 1 | cut -d: -f2- | tr -d ' \r\n')"
STDERR_B64="${'$'}(grep -i '^X-Stderr-B64:' "${'$'}HDR_TMP" | tail -n 1 | cut -d: -f2- | tr -d ' \r\n')"

if [ -n "${'$'}STDERR_B64" ]; then
    if command -v base64 >/dev/null 2>&1; then
        printf '%s' "${'$'}STDERR_B64" | base64 -d >&2 2>/dev/null || true
    elif command -v python3 >/dev/null 2>&1; then
        python3 -c "import sys,base64; sys.stderr.buffer.write(base64.b64decode(sys.argv[1]))" "${'$'}STDERR_B64" || true
    fi
fi

cat "${'$'}OUT_TMP"
exit "${'$'}{EXIT_CODE:-1}"
"""
    }
}

data class RootfsPatchOptions(
    val nameservers: List<String> = emptyList(),
    val hostname: String = "localhost",
    val locale: String = "C.UTF-8",
    val groupIds: List<Long> = emptyList(),
)
