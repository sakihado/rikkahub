package me.rerere.workspace

import java.io.File
import java.nio.file.Files

class RootfsPatcher {
    fun patch(
        linuxDir: File,
        options: RootfsPatchOptions = RootfsPatchOptions(),
    ) {
        val etcDir = File(linuxDir, "etc")
        if (!etcDir.isDirectory) return

        ensureRootfsDns(etcDir, options.nameservers)
        ensureHosts(etcDir, options.hostname)
        ensureHostname(etcDir, options.hostname)
        ensureLocale(etcDir, options.locale)
        ensureGroupNames(etcDir, options.groupIds.ifEmpty { currentSupplementaryGroupIds() })
        ensureTempDirs(linuxDir)
        ensureHostBridgeScripts(linuxDir)
    }

    private fun ensureRootfsDns(
        etcDir: File,
        nameservers: List<String>,
    ) {
        val resolvConf = File(etcDir, "resolv.conf")
        val shouldWrite = when {
            Files.isSymbolicLink(resolvConf.toPath()) -> true
            !resolvConf.exists() -> true
            !resolvConf.isFile -> true
            else -> resolvConf.readText()
                .lineSequence()
                .filter { it.trimStart().startsWith("nameserver ") }
                .none { line ->
                    val server = line.trim().removePrefix("nameserver").trim()
                    server.isNotBlank() && server !in LOCAL_RESOLVERS
                }
        }
        if (!shouldWrite) return

        if (resolvConf.exists() || Files.isSymbolicLink(resolvConf.toPath())) {
            resolvConf.delete()
        }

        val servers = nameservers
            .filter { it.isNotBlank() }
            .distinct()
            .take(MAX_DNS_SERVERS)
            .ifEmpty { DEFAULT_DNS_SERVERS }

        resolvConf.writeText(
            buildString {
                appendLine("# Generated by RikkaHub workspace.")
                servers.forEach { appendLine("nameserver $it") }
                appendLine("options edns0 trust-ad")
            }
        )
    }

    private fun ensureHosts(etcDir: File, hostname: String) {
        val hosts = File(etcDir, "hosts")
        val lines = if (hosts.isFile) hosts.readLines() else emptyList()
        val hasIpv4Localhost = lines.any { line ->
            val normalized = line.substringBefore('#').trim().split(WHITESPACE_REGEX)
            normalized.firstOrNull() == "127.0.0.1" && "localhost" in normalized.drop(1)
        }
        val hasIpv6Localhost = lines.any { line ->
            val normalized = line.substringBefore('#').trim().split(WHITESPACE_REGEX)
            normalized.firstOrNull() == "::1" && "localhost" in normalized.drop(1)
        }
        if (hasIpv4Localhost && hasIpv6Localhost) return

        hosts.parentFile?.mkdirs()
        hosts.appendText(
            buildString {
                if (hosts.exists() && hosts.length() > 0 && !hosts.readText().endsWith('\n')) {
                    appendLine()
                }
                if (!hasIpv4Localhost) {
                    append("127.0.0.1 localhost")
                    if (hostname.isNotBlank() && hostname != "localhost") {
                        append(" ")
                        append(hostname)
                    }
                    appendLine()
                }
                if (!hasIpv6Localhost) {
                    appendLine("::1 localhost ip6-localhost ip6-loopback")
                }
            }
        )
    }

    private fun ensureHostname(etcDir: File, hostname: String) {
        val target = File(etcDir, "hostname")
        if (target.isFile && target.readText().trim().isNotBlank()) return
        target.writeText("${hostname.ifBlank { DEFAULT_HOSTNAME }}\n")
    }

    private fun ensureLocale(etcDir: File, locale: String) {
        val defaultDir = File(etcDir, "default").apply { mkdirs() }
        val target = File(defaultDir, "locale")
        val lines = if (target.isFile) target.readLines().toMutableList() else mutableListOf()
        if (lines.any { it.trim().startsWith("LANG=") }) return
        lines += "LANG=$locale"
        target.writeText(lines.joinToString(separator = "\n", postfix = "\n"))
    }

    private fun ensureGroupNames(etcDir: File, groupIds: List<Long>) {
        val target = File(etcDir, "group")
        if (!target.exists()) {
            target.writeText("root:x:0:\n")
        }
        val lines = target.readLines().toMutableList()
        val existingIds = lines.mapNotNull { line ->
            line.split(':').getOrNull(2)?.toLongOrNull()
        }.toSet()
        val existingNames = lines.mapNotNull { line ->
            line.substringBefore(':').takeIf { it.isNotBlank() }
        }.toSet()
        val additions = groupIds
            .filter { it > 0 && it !in existingIds }
            .distinct()
            .map { id ->
                val baseName = "android_gid_$id"
                val name = if (baseName in existingNames) "${baseName}_workspace" else baseName
                "$name:x:$id:"
            }
        if (additions.isEmpty()) return

        target.appendText(
            buildString {
                if (target.length() > 0 && !target.readText().endsWith('\n')) {
                    appendLine()
                }
                additions.forEach { appendLine(it) }
            }
        )
    }

    private fun ensureTempDirs(linuxDir: File) {
        listOf("tmp", "var/tmp", "root").forEach { path ->
            File(linuxDir, path).mkdirs()
        }
        listOf(File(linuxDir, "tmp"), File(linuxDir, "var/tmp")).forEach { dir ->
            dir.setReadable(true, false)
            dir.setWritable(true, false)
            dir.setExecutable(true, false)
        }
        File(linuxDir, "root").apply {
            setReadable(true, true)
            setWritable(true, true)
            setExecutable(true, true)
        }
    }

    /**
     * 在 Rootfs 的 `/usr/local/` 下安装：
     * 1. `host-sh`（及别名 `rish`）：通过本地桥接守护进程调用 Android 宿主机命令，stdout 字节流无损回传。
     * 2. `/usr/local/libexec/rikkahub-sdcard-trash`：统一的 `/sdcard` 防误删回收站核心逻辑（防碰撞、防二次删除）。
     * 3. `rm` / `rmdir` / `unlink` 包装器：操作 `/workspace`、`/tmp` 时保留 100% 原始选项语义透传；
     *    一旦目标解析到 `/sdcard` 或 `/storage`，统一委托给回收站 helper 整块移入 `/sdcard/.Trash-RikkaHub/`。
     */
    private fun ensureHostBridgeScripts(linuxDir: File) {
        val binDir = File(linuxDir, "usr/local/bin").apply { mkdirs() }
        val libexecDir = File(linuxDir, "usr/local/libexec").apply { mkdirs() }

        writeExecutableIfChanged(File(binDir, "host-sh"), HOST_SH_SCRIPT)
        writeExecutableIfChanged(File(binDir, "rish"), RISH_WRAPPER_SCRIPT)
        writeExecutableIfChanged(File(libexecDir, "rikkahub-sdcard-trash"), SDCARD_TRASH_HELPER_SCRIPT)
        writeExecutableIfChanged(File(binDir, "rm"), SAFE_RM_SCRIPT)
        writeExecutableIfChanged(File(binDir, "rmdir"), SAFE_RMDIR_SCRIPT)
        writeExecutableIfChanged(File(binDir, "unlink"), SAFE_UNLINK_SCRIPT)
    }

    private fun writeExecutableIfChanged(file: File, content: String) {
        if (Files.isSymbolicLink(file.toPath())) {
            file.delete()
        }
        if (!file.isFile || file.readText() != content) {
            file.writeText(content)
        }
        file.setReadable(true, false)
        file.setWritable(true, true)
        file.setExecutable(true, false)
    }

    private fun currentSupplementaryGroupIds(): List<Long> {
        val status = File("/proc/self/status")
        if (!status.isFile) return emptyList()
        val groups = status.readLines().firstOrNull { it.startsWith("Groups:") } ?: return emptyList()
        return groups
            .removePrefix("Groups:")
            .trim()
            .split(WHITESPACE_REGEX)
            .mapNotNull { it.toLongOrNull() }
    }

    private companion object {
        private const val MAX_DNS_SERVERS = 3
        private const val DEFAULT_HOSTNAME = "localhost"
        private val WHITESPACE_REGEX = Regex("\\s+")
        private val LOCAL_RESOLVERS = setOf(
            "127.0.0.1",
            "127.0.0.53",
            "::1",
        )
        private val DEFAULT_DNS_SERVERS = listOf(
            "1.1.1.1",
            "8.8.8.8",
            "223.5.5.5",
        )

        private val HOST_SH_SCRIPT = """
            #!/bin/sh
            # Execute a read-only diagnostic command on the real Android host via RikkaHub HostBridgeDaemon
            ENDPOINT_FILE="/run/host_bridge/endpoint"
            if [ ! -f "${'$'}ENDPOINT_FILE" ]; then
              echo "host-sh: /run/host_bridge/endpoint not found (host bridge not running)" >&2
              exit 125
            fi

            AS_ROOT="false"
            TIMEOUT_SEC="45"
            while [ "${'$'}#" -gt 0 ]; do
              case "${'$'}1" in
                -r|--root)
                  AS_ROOT="true"
                  shift
                  ;;
                -t|--timeout)
                  TIMEOUT_SEC="${'$'}2"
                  shift 2
                  ;;
                -c)
                  shift
                  break
                  ;;
                --)
                  shift
                  break
                  ;;
                *)
                  break
                  ;;
              esac
            done

            if [ "${'$'}#" -eq 0 ]; then
              CMD="${'$'}(cat)"
            else
              CMD="${'$'}*"
            fi

            if [ -z "${'$'}CMD" ]; then
              echo "Usage: host-sh [-r] [-t seconds] \"<android_command>\"" >&2
              exit 2
            fi

            PORT="${'$'}(grep '^PORT=' "${'$'}ENDPOINT_FILE" | cut -d= -f2)"
            TOKEN="${'$'}(grep '^TOKEN=' "${'$'}ENDPOINT_FILE" | cut -d= -f2)"

            HDR_FILE="${'$'}(mktemp /tmp/hostsh_hdr.XXXXXX)"
            cleanup() { /bin/rm -f "${'$'}HDR_FILE"; }
            trap cleanup EXIT INT TERM

            if command -v curl >/dev/null 2>&1; then
              printf '%s' "${'$'}CMD" | curl -sS --max-time "${'$'}((TIMEOUT_SEC + 5))" \
                -D "${'$'}HDR_FILE" \
                -H "Expect:" \
                -H "X-Bridge-Token: ${'$'}TOKEN" \
                -H "X-As-Root: ${'$'}AS_ROOT" \
                -H "X-Timeout-Sec: ${'$'}TIMEOUT_SEC" \
                --data-binary @- \
                "http://127.0.0.1:${'$'}PORT/exec"
              RC=${'$'}?
            else
              echo "host-sh: curl is required inside Rootfs" >&2
              exit 127
            fi

            if [ "${'$'}RC" -ne 0 ]; then
              echo "host-sh: bridge request failed (curl exit ${'$'}RC)" >&2
              exit 125
            fi

            STDERR_B64="${'$'}(awk 'BEGIN{IGNORECASE=1} /^X-Stderr-B64:/ {sub(/\r${'$'}/, ""); print ${'$'}2}' "${'$'}HDR_FILE")"
            if [ -n "${'$'}STDERR_B64" ]; then
              printf '%s' "${'$'}STDERR_B64" | base64 -d >&2 2>/dev/null
            fi

            EXIT_CODE="${'$'}(awk 'BEGIN{IGNORECASE=1} /^X-Exit-Code:/ {sub(/\r${'$'}/, ""); print ${'$'}2}' "${'$'}HDR_FILE")"
            exit "${'$'}{EXIT_CODE:-1}"
        """.trimIndent() + "\n"

        private val RISH_WRAPPER_SCRIPT = """
            #!/bin/sh
            exec /usr/local/bin/host-sh "${'$'}@"
        """.trimIndent() + "\n"

        /**
         * 统一回收站逻辑（供 rm / rmdir / unlink 共享调用）：
         * 参数: <tool_name> <mode:rm|rmdir|unlink> <force:0|1> <recursive:0|1> <dir_flag:0|1> <target> <resolved>
         * 每次移入均寻找唯一不存在的目标名（纳秒/秒 + PID + 递增序号），绝不覆盖已有同名备份。
         */
        private val SDCARD_TRASH_HELPER_SCRIPT = """
            #!/bin/sh
            TOOL="${'$'}1"
            MODE="${'$'}2"
            FORCE="${'$'}3"
            RECURSIVE="${'$'}4"
            DIR_FLAG="${'$'}5"
            TARGET="${'$'}6"
            RESOLVED="${'$'}7"
            TRASH_DIR="/sdcard/.Trash-RikkaHub"

            case "${'$'}RESOLVED" in
              /sdcard|/storage/emulated/0)
                echo "${'$'}TOOL: refusing to remove root storage directory '${'$'}TARGET'" >&2
                exit 1
                ;;
              /sdcard/.Trash-RikkaHub|/sdcard/.Trash-RikkaHub/*|/storage/emulated/0/.Trash-RikkaHub|/storage/emulated/0/.Trash-RikkaHub/*)
                echo "${'$'}TOOL: refusing to permanently delete files inside '${'$'}TRASH_DIR'" >&2
                exit 1
                ;;
            esac

            if [ ! -e "${'$'}TARGET" ] && [ ! -L "${'$'}TARGET" ]; then
              if [ "${'$'}FORCE" -eq 1 ]; then
                exit 0
              fi
              echo "${'$'}TOOL: cannot remove '${'$'}TARGET': No such file or directory" >&2
              exit 1
            fi

            if [ "${'$'}MODE" = "unlink" ]; then
              if [ -d "${'$'}TARGET" ] && [ ! -L "${'$'}TARGET" ]; then
                echo "unlink: cannot unlink '${'$'}TARGET': Is a directory" >&2
                exit 1
              fi
            elif [ "${'$'}MODE" = "rmdir" ]; then
              if [ -L "${'$'}TARGET" ] || [ ! -d "${'$'}TARGET" ]; then
                echo "rmdir: failed to remove '${'$'}TARGET': Not a directory" >&2
                exit 1
              fi
              if [ -n "${'$'}(ls -A -- "${'$'}TARGET" 2>/dev/null)" ]; then
                echo "rmdir: failed to remove '${'$'}TARGET': Directory not empty" >&2
                exit 1
              fi
            elif [ "${'$'}MODE" = "rm" ]; then
              if [ -d "${'$'}TARGET" ] && [ ! -L "${'$'}TARGET" ] && [ "${'$'}RECURSIVE" -eq 0 ]; then
                if [ "${'$'}DIR_FLAG" -eq 0 ]; then
                  echo "rm: cannot remove '${'$'}TARGET': Is a directory" >&2
                  exit 1
                fi
                if [ -n "${'$'}(ls -A -- "${'$'}TARGET" 2>/dev/null)" ]; then
                  echo "rm: cannot remove '${'$'}TARGET': Directory not empty" >&2
                  exit 1
                fi
              fi
            fi

            mkdir -p "${'$'}TRASH_DIR" || exit 1
            CLEAN_TARGET="${'$'}TARGET"
            case "${'$'}CLEAN_TARGET" in
              ?*/) CLEAN_TARGET="${'$'}(printf '%s' "${'$'}CLEAN_TARGET" | sed 's:/*${'$'}::')" ;;
            esac
            BASE="${'$'}(basename -- "${'$'}CLEAN_TARGET")"
            [ -z "${'$'}BASE" ] && BASE="item"

            STAMP="${'$'}(date +%Y%m%d_%H%M%S_%N 2>/dev/null)"
            case "${'$'}STAMP" in
              *%N*|"") STAMP="${'$'}(date +%Y%m%d_%H%M%S)_${'$'}${'$'}" ;;
            esac

            SEQ=0
            while :; do
              if [ "${'$'}SEQ" -eq 0 ]; then
                DEST="${'$'}TRASH_DIR/${'$'}{STAMP}_${'$'}${'$'}_${'$'}{BASE}"
              else
                DEST="${'$'}TRASH_DIR/${'$'}{STAMP}_${'$'}${'$'}_${'$'}{SEQ}_${'$'}{BASE}"
              fi
              if [ ! -e "${'$'}DEST" ] && [ ! -L "${'$'}DEST" ]; then
                break
              fi
              SEQ=${'$'}((SEQ + 1))
            done

            mv -n -- "${'$'}TARGET" "${'$'}DEST" 2>/dev/null || mv -- "${'$'}TARGET" "${'$'}DEST" || exit 1
            if [ -e "${'$'}TARGET" ] || [ -L "${'$'}TARGET" ]; then
              echo "${'$'}TOOL: refused overwrite while moving '${'$'}TARGET' to trash" >&2
              exit 1
            fi
            exit 0
        """.trimIndent() + "\n"

        private val SAFE_RM_SCRIPT = """
            #!/bin/sh
            # Protect /sdcard paths via trash while preserving 100% native rm flags on non-/sdcard paths
            REAL_RM="/bin/rm"
            [ -x "/usr/bin/rm" ] && [ ! -x "${'$'}REAL_RM" ] && REAL_RM="/usr/bin/rm"
            HELPER="/usr/local/libexec/rikkahub-sdcard-trash"

            resolve_target() {
              p="${'$'}1"
              case "${'$'}p" in
                ?*/) p="${'$'}(printf '%s' "${'$'}p" | sed 's:/*${'$'}::')" ;;
              esac
              parent="${'$'}(dirname -- "${'$'}p")"
              leaf="${'$'}(basename -- "${'$'}p")"
              rp="${'$'}(realpath -m -- "${'$'}parent" 2>/dev/null || printf '%s' "${'$'}parent")"
              if [ "${'$'}leaf" = "/" ] || [ "${'$'}leaf" = "." ]; then
                realpath -m -- "${'$'}p" 2>/dev/null || printf '%s' "${'$'}p"
              elif [ "${'$'}rp" = "/" ]; then
                printf '/%s' "${'$'}leaf"
              else
                printf '%s/%s' "${'$'}rp" "${'$'}leaf"
              fi
            }

            is_sdcard() {
              case "${'$'}1" in
                /sdcard|/sdcard/*|/storage/emulated/0|/storage/emulated/0/*) return 0 ;;
                *) return 1 ;;
              esac
            }

            FORCE=0
            RECURSIVE=0
            DIR_FLAG=0
            END_OPTS=0
            HAS_SDCARD=0
            HAS_TARGET=0

            for arg in "${'$'}@"; do
              if [ "${'$'}END_OPTS" -eq 0 ]; then
                case "${'$'}arg" in
                  --) END_OPTS=1; continue ;;
                  --force) FORCE=1; continue ;;
                  --recursive) RECURSIVE=1; continue ;;
                  --dir) DIR_FLAG=1; continue ;;
                  --help|--version) exec "${'$'}REAL_RM" "${'$'}@" ;;
                  --*) continue ;;
                  -?*)
                    opt="${'$'}{arg#-}"
                    while [ -n "${'$'}opt" ]; do
                      ch="${'$'}(printf '%s' "${'$'}opt" | cut -c1)"
                      opt="${'$'}(printf '%s' "${'$'}opt" | cut -c2-)"
                      case "${'$'}ch" in
                        f) FORCE=1 ;;
                        r|R) RECURSIVE=1 ;;
                        d) DIR_FLAG=1 ;;
                      esac
                    done
                    continue
                    ;;
                esac
              fi
              HAS_TARGET=1
              RES="${'$'}(resolve_target "${'$'}arg")"
              if is_sdcard "${'$'}RES"; then
                HAS_SDCARD=1
              fi
            done

            if [ "${'$'}HAS_TARGET" -eq 0 ] || [ "${'$'}HAS_SDCARD" -eq 0 ]; then
              exec "${'$'}REAL_RM" "${'$'}@"
            fi

            # Position-independent argument partitioning:
            # 1) Collect all option flags anywhere before `--` (supporting trailing options like `rm /sdcard/a /ws/dir -rf`)
            # 2) Append `--`
            # 3) Dispatch `/sdcard` targets to trash helper and append non-`/sdcard` targets after `--`
            ORIG_COUNT=${'$'}#
            END_OPTS=0
            IDX=1
            while [ "${'$'}IDX" -le "${'$'}ORIG_COUNT" ]; do
              eval "arg=\${'$'}{${'$'}IDX}"
              IDX=${'$'}((IDX + 1))
              if [ "${'$'}END_OPTS" -eq 0 ]; then
                case "${'$'}arg" in
                  --) END_OPTS=1; continue ;;
                  -?*) set -- "${'$'}@" "${'$'}arg"; continue ;;
                esac
              fi
            done

            set -- "${'$'}@" "--"

            STATUS=0
            NON_SD_COUNT=0
            END_OPTS=0
            IDX=1
            while [ "${'$'}IDX" -le "${'$'}ORIG_COUNT" ]; do
              eval "arg=\${'$'}{${'$'}IDX}"
              IDX=${'$'}((IDX + 1))
              if [ "${'$'}END_OPTS" -eq 0 ]; then
                case "${'$'}arg" in
                  --) END_OPTS=1; continue ;;
                  -?*) continue ;;
                esac
              fi
              RES="${'$'}(resolve_target "${'$'}arg")"
              if is_sdcard "${'$'}RES"; then
                "${'$'}HELPER" "rm" "rm" "${'$'}FORCE" "${'$'}RECURSIVE" "${'$'}DIR_FLAG" "${'$'}arg" "${'$'}RES" || STATUS=1
              else
                set -- "${'$'}@" "${'$'}arg"
                NON_SD_COUNT=${'$'}((NON_SD_COUNT + 1))
              fi
            done

            shift "${'$'}ORIG_COUNT"

            if [ "${'$'}NON_SD_COUNT" -gt 0 ]; then
              "${'$'}REAL_RM" "${'$'}@" || STATUS=${'$'}?
            fi

            exit "${'$'}STATUS"
        """.trimIndent() + "\n"

        private val SAFE_RMDIR_SCRIPT = """
            #!/bin/sh
            REAL_RMDIR="/bin/rmdir"
            [ -x "/usr/bin/rmdir" ] && [ ! -x "${'$'}REAL_RMDIR" ] && REAL_RMDIR="/usr/bin/rmdir"
            HELPER="/usr/local/libexec/rikkahub-sdcard-trash"

            END_OPTS=0
            HAS_SDCARD=0
            for arg in "${'$'}@"; do
              if [ "${'$'}END_OPTS" -eq 0 ]; then
                case "${'$'}arg" in
                  --) END_OPTS=1; continue ;;
                  --help|--version) exec "${'$'}REAL_RMDIR" "${'$'}@" ;;
                  -?*) continue ;;
                esac
              fi
              RESOLVED="${'$'}(realpath -m -- "${'$'}arg" 2>/dev/null || printf '%s' "${'$'}arg")"
              case "${'$'}RESOLVED" in
                /sdcard|/sdcard/*|/storage/emulated/0|/storage/emulated/0/*) HAS_SDCARD=1 ;;
              esac
            done

            if [ "${'$'}HAS_SDCARD" -eq 0 ]; then
              exec "${'$'}REAL_RMDIR" "${'$'}@"
            fi

            STATUS=0
            END_OPTS=0
            for arg in "${'$'}@"; do
              if [ "${'$'}END_OPTS" -eq 0 ]; then
                case "${'$'}arg" in
                  --) END_OPTS=1; continue ;;
                  -?*) continue ;;
                esac
              fi
              RESOLVED="${'$'}(realpath -m -- "${'$'}arg" 2>/dev/null || printf '%s' "${'$'}arg")"
              case "${'$'}RESOLVED" in
                /sdcard|/sdcard/*|/storage/emulated/0|/storage/emulated/0/*)
                  "${'$'}HELPER" "rmdir" "rmdir" 0 0 1 "${'$'}arg" "${'$'}RESOLVED" || STATUS=1
                  ;;
                *)
                  "${'$'}REAL_RMDIR" -- "${'$'}arg" || STATUS=1
                  ;;
              esac
            done
            exit "${'$'}STATUS"
        """.trimIndent() + "\n"

        private val SAFE_UNLINK_SCRIPT = """
            #!/bin/sh
            REAL_UNLINK="/usr/bin/unlink"
            [ -x "/bin/unlink" ] && [ ! -x "${'$'}REAL_UNLINK" ] && REAL_UNLINK="/bin/unlink"
            HELPER="/usr/local/libexec/rikkahub-sdcard-trash"

            if [ "${'$'}#" -eq 1 ]; then
              case "${'$'}1" in
                --help|--version) exec "${'$'}REAL_UNLINK" "${'$'}@" ;;
              esac
              p="${'$'}1"
              parent="${'$'}(dirname -- "${'$'}p")"
              leaf="${'$'}(basename -- "${'$'}p")"
              rp="${'$'}(realpath -m -- "${'$'}parent" 2>/dev/null || printf '%s' "${'$'}parent")"
              if [ "${'$'}rp" = "/" ]; then RESOLVED="/${'$'}leaf"; else RESOLVED="${'$'}rp/${'$'}leaf"; fi
              case "${'$'}RESOLVED" in
                /sdcard|/sdcard/*|/storage/emulated/0|/storage/emulated/0/*)
                  exec "${'$'}HELPER" "unlink" "unlink" 0 0 0 "${'$'}1" "${'$'}RESOLVED"
                  ;;
              esac
            fi
            exec "${'$'}REAL_UNLINK" "${'$'}@"
        """.trimIndent() + "\n"
    }
}

data class RootfsPatchOptions(
    val nameservers: List<String> = emptyList(),
    val hostname: String = "localhost",
    val locale: String = "C.UTF-8",
    val groupIds: List<Long> = emptyList(),
)
